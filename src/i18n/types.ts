/**
 * 某个语言包文件必须满足的形状：键集与中文包**完全一致**，值全部是字符串。
 *
 * 键集一致性由 `Record<keyof typeof zh, string>` 在编译期保证——
 * 漏翻一个键会直接 `vue-tsc` 报错，而不是上线后让用户看到裸中文。
 * 值只约束「是字符串」，不约束内容，所以两种语言可以写得完全不同。
 */
export type DictOf<Z> = Record<keyof Z, string>;
