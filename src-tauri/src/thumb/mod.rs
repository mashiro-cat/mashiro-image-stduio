//! 缩略图域：把原始大图缩成列表能吃得下的小图。
//!
//! # 为什么不直接让前端加载原图
//!
//! 本机实测 `images/` 里有 **126MB 的 8192×8192 PNG**（4× 超分产物）。
//! WebView 加载 `asset://` 时要把整份文件读进 WebView 再解码，
//! 8192² 的位图光解码后就是 8192×8192×4 ≈ **256MB**，
//! 历史记录一屏几十张同时加载——直接把渲染进程主线程占死，
//! 表现就是「整个软件卡住」，不是某个页面慢。
//!
//! 所以列表类场景一律先过这里拿缩略图：512px 的 JPEG 只有几十 KB，
//! 解码成本可以忽略。**原图只在用户主动要看时（大图查看器 1:1）才加载。**
//!
//! # 分工
//!
//! - [`cache`]：缩略图落盘位置 + 缓存有效性判定
//! - [`render`]：解码 → 缩放 → 编码 JPEG（纯计算，不碰路径）
//! - [`commands`]：IPC 薄封装
//!
//! # 关键约束：必须限并发
//!
//! 解码一张 8192² 的 PNG 峰值要吃掉 256MB 内存。历史记录滚动时会同时
//! 请求几十张缩略图，无节制并发会把内存打爆（表现为整个应用被系统换页）。
//! 因此 [`commands`] 用信号量把并发压到 [`MAX_CONCURRENT`]，
//! 其余请求排队等——**宁可慢，也不能卡死**。

pub(crate) mod cache;
pub(crate) mod commands;
pub(crate) mod render;

#[cfg(test)]
mod integration;

/// 同时解码的最大张数。
///
/// 2 是权衡：一张 8192² 的 RGBA 位图是 256MiB，解码峰值按
/// [`render::MAX_ALLOC`]（320MiB）算，2 张就是 640MiB——
/// 已经是普通机器能安全承受的上限。再高没有可感知的收益，
/// 瓶颈是单张解码本身而不是排队。
pub(crate) const MAX_CONCURRENT: usize = 2;

/// 前端请求的缩略图长边上限（像素）。
///
/// 超过这个值就按它来，防止前端（或将来误写的调用方）
/// 传一个 8192 进来把「缩略图」又变成了原图。
pub(crate) const MAX_EDGE_LIMIT: u32 = 2048;
